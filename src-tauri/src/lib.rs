#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    init_tracing();

    let config = Arc::new(AppConfig::load());

    let specta = specta_builder();
    #[cfg(debug_assertions)]
    specta
        .export(
            specta_typescript::Typescript::default()
                .bigint(specta_typescript::BigIntExportBehavior::Number)
                .header("// @ts-nocheck\n// Generated by tauri-specta. DO NOT EDIT.\n"),
            "../src/shared/api/bindings.ts",
        )
        .expect("failed to export typescript bindings");

    tauri::Builder::default()
        .plugin(tauri_plugin_os::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .setup({
            let config = config.clone();
            move |app| {
                let app_data_dir = app
                    .path()
                    .app_data_dir()
                    .map_err(|e| format!("could not resolve app data dir: {e}"))?;
                std::fs::create_dir_all(&app_data_dir)
                    .map_err(|e| format!("could not create app data dir: {e}"))?;

                let db_path = config.db_path(&app_data_dir);
                tracing::info!(?db_path, "opening sqlite database");

                let db = db::DbPool::open(&db_path)
                    .map_err(|e| format!("failed to open sqlite pool: {e}"))?;
                db.run_migrations()
                    .map_err(|e| format!("failed to run migrations: {e}"))?;

                let http = http_client::HttpClient::new(config.clone(), app_data_dir.clone())
                    .map_err(|e| format!("failed to build http client: {e}"))?;

                let db = Arc::new(db);
                let http = Arc::new(http);
                let state = AppState {
                    config: config.clone(),
                    db: db.clone(),
                    http: http.clone(),
                    data_dir: app_data_dir,
                };
                app.manage(state.clone());

                // The sync engine is host-driven: writes kick it, the UI can
                // call sync_now, and a modest heartbeat drains stragglers whose
                // backoff gate has passed. No blind fire-into-the-void loops.
                let engine = Arc::new(services::engine::SyncEngine::new(
                    db,
                    http,
                    config.sync.push_batch_size,
                    config.sync.pull_limit,
                ));
                app.manage(commands::sync::EngineState(engine.clone()));
                let heartbeat = config.sync.heartbeat_interval;
                let boot_state = state.clone();
                tauri::async_runtime::spawn(async move {
                    // First run: recover inflight strandings, then push+pull.
                    let _ = engine.drain().await;
                    let _ = engine.pull().await;
                    // With a live session, refresh every mirror best-effort —
                    // a fresh install / second PC must not show an empty app
                    // until someone finds the Settings refresh button.
                    if session_store::read_jwt(&boot_state.data_dir).ok().flatten().is_some() {
                        commands::online::refresh_all_mirrors(&boot_state).await;
                    }
                    loop {
                        tokio::time::sleep(heartbeat).await;
                        let Ok(s) = engine.status() else { continue };
                        if s.pending > 0 || s.inflight > 0 {
                            let _ = engine.drain().await;
                        } else if !s.online && !s.auth_paused {
                            // Empty queue + offline flag: a drain makes no
                            // network call, so the flag would stick forever.
                            // A pull both probes AND refreshes — success
                            // marks the engine online again.
                            let _ = engine.pull().await;
                        }
                    }
                });

                Ok(())
            }
        })
        .invoke_handler(specta.invoke_handler())
        .run(tauri::generate_context!())
        .expect("error while running apex-maintenance");
}

fn init_tracing() {
    let filter = EnvFilter::try_from_default_env()
        .unwrap_or_else(|_| EnvFilter::new("info,apex_maintenance_lib=debug"));

    tracing_subscriber::registry()
        .with(filter)
        .with(tracing_subscriber::fmt::layer().with_target(true).compact())
        .init();
}


#[cfg(test)]
mod codegen_tests {
    /// Running `cargo test` regenerates the TypeScript bindings, so CI and
    /// local runs both fail loudly if the generated file was hand-edited or
    /// went stale relative to the command surface.
    #[test]
    fn typescript_bindings_export() {
        super::specta_builder()
            .export(
                specta_typescript::Typescript::default()
                    // i64 → number: every i64 we ship (ids, odometers, counts)
                    // is far below 2^53, and Tauri's IPC serializes them as
                    // JSON numbers anyway.
                    .bigint(specta_typescript::BigIntExportBehavior::Number)
                    .header("// @ts-nocheck\n// Generated by tauri-specta. DO NOT EDIT.\n"),
                "../src/shared/api/bindings.ts",
            )
            .expect("failed to export typescript bindings");
    }
}
